const FR_MONTHS = {
  janvier: 1, février: 2, fevrier: 2, mars: 3, avril: 4, mai: 5, juin: 6,
  juillet: 7, août: 8, aout: 8, septembre: 9, octobre: 10, novembre: 11, décembre: 12, decembre: 12
};

/**
 * Convertit une date d'article ("11 Avril 2026" / "April 11, 2026") en ISO "YYYY-MM-DD".
 */
export function blogDateToISO(dateStr) {
  if (!dateStr) return "2026-04-11";
  const frMatch = dateStr.trim().match(/^(\d{1,2})\s+([^\s]+)\s+(\d{4})$/);
  if (frMatch) {
    const month = FR_MONTHS[frMatch[2].toLowerCase()];
    if (month) {
      return `${frMatch[3]}-${String(month).padStart(2, "0")}-${frMatch[1].padStart(2, "0")}`;
    }
  }
  const parsed = new Date(dateStr);
  if (!Number.isNaN(parsed.getTime())) {
    // Utilise les composantes LOCALES de la date parsée (minuit local),
    // sans conversion UTC qui pourrait décaler d'un jour selon le fuseau du build.
    const y = parsed.getFullYear();
    const m = String(parsed.getMonth() + 1).padStart(2, "0");
    const d = String(parsed.getDate()).padStart(2, "0");
    return `${y}-${m}-${d}`;
  }
  return "2026-04-11";
}
